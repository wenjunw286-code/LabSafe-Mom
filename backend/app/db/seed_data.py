def seed_database(db):
    """Seed the hazardous_substances table if empty."""
    from app.models.substance import HazardousSubstance

    count = db.query(HazardousSubstance).count()
    if count > 0:
        return  # Already seeded

    for item in SEED_SUBSTANCES:
        substance = HazardousSubstance(**item)
        db.add(substance)

    db.commit()
    print(f"Seeded {len(SEED_SUBSTANCES)} hazardous substances into database.")
